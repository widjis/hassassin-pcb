/**
 * Gerber RS-274X (with X2 file attributes) writer. Coordinates: mm, format 4.6,
 * Y flipped (Gerber Y points up; the document's Y points down).
 */
import {
  arcPoints,
  frameOf,
  toWorld,
  type CopperShape,
  type Doc,
  type StyleEngine,
  type Vec2,
} from '@hassassin/core';

const n6 = (v: number) => Math.round(v * 1e6).toString();
const X = (p: Vec2) => `X${n6(p.x)}Y${n6(-p.y)}`;
const fmt = (v: number) => v.toFixed(6);

export interface GerberLayerSpec {
  /** Document layer name, e.g. F.Cu */
  layer: string;
  /** X2 file function, e.g. "Copper,L1,Top" */
  fileFunction: string;
  polarity?: 'Positive' | 'Negative';
}

class Writer {
  private lines: string[] = [];
  private apertures = new Map<string, number>();
  private body: string[] = [];
  private current = -1;
  private next = 10;

  constructor(spec: GerberLayerSpec, title: string) {
    this.lines.push(
      `G04 ${title} — ${spec.layer} — generated by Hassassin PCB*`,
      '%TF.GenerationSoftware,Hassassin,PCB,0.2*%',
      `%TF.FileFunction,${spec.fileFunction}*%`,
      `%TF.FilePolarity,${spec.polarity ?? 'Positive'}*%`,
      '%FSLAX46Y46*%',
      '%MOMM*%',
      '%LPD*%',
    );
  }

  private ap(diameter: number): number {
    const key = fmt(Math.max(diameter, 0.001));
    let d = this.apertures.get(key);
    if (d === undefined) {
      d = this.next++;
      this.apertures.set(key, d);
    }
    return d;
  }

  private use(d: number): void {
    if (this.current !== d) {
      this.body.push(`D${d}*`);
      this.current = d;
    }
  }

  polarity(dark: boolean): void {
    this.body.push(dark ? '%LPD*%' : '%LPC*%');
  }

  /** Stroke a polyline with a round aperture. */
  stroke(pts: Vec2[], width: number, closed = false): void {
    if (pts.length < 2) return;
    this.use(this.ap(width));
    this.body.push(`${X(pts[0]!)}D02*`);
    for (let i = 1; i < pts.length; i++) this.body.push(`${X(pts[i]!)}D01*`);
    if (closed) this.body.push(`${X(pts[0]!)}D01*`);
  }

  flashCircle(c: Vec2, diameter: number): void {
    this.use(this.ap(diameter));
    this.body.push(`${X(c)}D03*`);
  }

  region(ring: Vec2[]): void {
    if (ring.length < 3) return;
    this.body.push('G36*', `${X(ring[0]!)}D02*`);
    for (let i = 1; i < ring.length; i++) this.body.push(`${X(ring[i]!)}D01*`);
    this.body.push(`${X(ring[0]!)}D01*`, 'G37*');
  }

  finish(): string {
    const ads = [...this.apertures].map(([dia, d]) => `%ADD${d}C,${dia}*%`);
    return [...this.lines, ...ads, 'G01*', ...this.body, 'M02*', ''].join('\n');
  }
}

export interface GerberInput {
  doc: Doc;
  engine: StyleEngine;
  shapes: CopperShape[];
  title: string;
}

/** Copper layer: pours (with cleared holes) first, then pads, tracks and vias. */
export function copperGerber(input: GerberInput, spec: GerberLayerSpec): string {
  const w = new Writer(spec, input.title);
  const on = input.shapes.filter((s) => s.layer === spec.layer);
  for (const s of on) {
    if (s.kind !== 'fill') continue;
    for (const poly of s.areas) {
      w.polarity(true);
      w.region(poly[0]!);
      if (poly.length > 1) {
        w.polarity(false);
        for (const hole of poly.slice(1)) w.region(hole);
      }
    }
  }
  w.polarity(true);
  for (const s of on) {
    if (s.kind === 'pad') for (const a of s.areas) w.region(a[0]!);
    else if (s.kind === 'trace') {
      for (const [a, b, r] of s.edges) w.stroke([a, b], r * 2);
    } else if (s.kind === 'via') {
      const [c, , r] = s.edges[0]!;
      w.flashCircle(c, r * 2);
    }
  }
  return w.finish();
}

/** Solder mask / paste openings: pads that list the layer (vias stay tented). */
export function padLayerGerber(input: GerberInput, spec: GerberLayerSpec, copper: string[]): string {
  const w = new Writer(spec, input.title);
  const { doc, engine } = input;
  for (const n of doc.nodes.values()) {
    if (n.type !== 'pad') continue;
    const raw = engine.get(n.uid, 'layers')?.value;
    const ls = Array.isArray(raw) ? (raw as string[]) : [];
    if (!ls.includes(spec.layer)) continue;
    // Reuse the copper outline of the same pad (any copper layer).
    const s = input.shapes.find((x) => x.uid === n.uid && x.kind === 'pad' && copper.includes(x.layer));
    if (s) w.region(s.areas[0]![0]!);
  }
  return w.finish();
}

/** Silkscreen, fabrication or outline layers: strokes of graphic objects. */
export function graphicsGerber(input: GerberInput, spec: GerberLayerSpec, defaultWidth = 0.15): string {
  const w = new Writer(spec, input.title);
  const { doc, engine } = input;
  const vec = (uid: string, k: string) => {
    const v = engine.get(uid, k)?.value;
    return v && typeof v === 'object' && 'x' in v ? (v as Vec2) : undefined;
  };
  for (const n of doc.nodes.values()) {
    if (!['line', 'arc', 'circle', 'polygon', 'rectangle'].includes(n.type)) continue;
    if (engine.get(n.uid, 'layer')?.value !== spec.layer) continue;
    if (engine.get(n.uid, 'visible')?.value === false) continue;
    const f = frameOf(doc, engine, n);
    const W = (p: Vec2) => toWorld(f, p);
    const width = Number(engine.get(n.uid, 'strokeWidth')?.value ?? defaultWidth) || defaultWidth;
    const filled = engine.get(n.uid, 'filled')?.value === true;
    if (n.type === 'line') {
      const a = vec(n.uid, 'start');
      const b = vec(n.uid, 'end');
      if (a && b) w.stroke([W(a), W(b)], width);
    } else if (n.type === 'arc') {
      const a = vec(n.uid, 'start');
      const m = vec(n.uid, 'mid');
      const b = vec(n.uid, 'end');
      if (a && m && b) w.stroke(arcPoints(W(a), W(m), W(b)), width);
    } else if (n.type === 'circle') {
      const c = vec(n.uid, 'center');
      const r = Number(engine.get(n.uid, 'radius')?.value ?? 0);
      if (!c || !(r > 0)) continue;
      const cw = W(c);
      const k = Math.max(32, Math.ceil(r * 16));
      const ring = Array.from({ length: k }, (_, i) => ({ x: cw.x + Math.cos((i / k) * 2 * Math.PI) * r, y: cw.y + Math.sin((i / k) * 2 * Math.PI) * r }));
      if (filled) w.region(ring);
      w.stroke(ring, width, true);
    } else {
      const pts = ((engine.get(n.uid, 'points')?.value as Vec2[]) ?? []).map(W);
      if (pts.length < 2) continue;
      if (filled && pts.length >= 3) w.region(pts);
      w.stroke(pts, width, true);
    }
  }
  return w.finish();
}
